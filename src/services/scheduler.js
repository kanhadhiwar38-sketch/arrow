import { db, logEvent, bumpStat } from '../lib/store.js';
import { writeContent } from './ai.js';
import { publishToAccount } from './connectors.js';
import { hydrate } from '../lib/accounts.js';

// ── Cron parsing (5-field: minute hour day-of-month month day-of-week) ──────
const RANGES = [
  [0, 59], // minute
  [0, 23], // hour
  [1, 31], // dom
  [1, 12], // month
  [0, 6], // dow (0=Sunday)
];

export function validateCron(expr) {
  const parts = String(expr || '').trim().split(/\s+/);
  if (parts.length !== 5) return { valid: false, error: 'Cron must have 5 fields' };
  for (let i = 0; i < 5; i++) {
    const [min, max] = RANGES[i];
    if (!fieldMatches(parts[i], min, max, true)) return { valid: false, error: `Invalid field: ${parts[i]}` };
  }
  return { valid: true };
}

function fieldMatches(field, min, max, structural = false) {
  for (const part of field.split(',')) {
    const [rangePart, stepPart] = part.split('/');
    if (stepPart !== undefined && !/^\d+$/.test(stepPart)) return false;
    if (rangePart === '*') continue;
    if (rangePart.includes('-')) {
      const [a, b] = rangePart.split('-').map(Number);
      if (Number.isNaN(a) || Number.isNaN(b)) return false;
      if (structural && (a < min || b > max)) return false;
    } else {
      const n = Number(rangePart);
      if (Number.isNaN(n)) return false;
      if (structural && (n < min || n > max)) return false;
    }
  }
  return true;
}

function matchesValue(field, value, min, max) {
  for (const part of field.split(',')) {
    const [rangePart, stepPart] = part.split('/');
    const step = stepPart ? Number(stepPart) : 1;
    if (rangePart === '*') {
      if ((value - min) % step === 0) return true;
      continue;
    }
    if (rangePart.includes('-')) {
      const [a, b] = rangePart.split('-').map(Number);
      const from = Math.max(a, min);
      if (value >= a && value <= b && (value - from) % step === 0) return true;
    } else if (Number(rangePart) === value) {
      return true;
    }
  }
  return false;
}

export function cronMatches(expr, date) {
  const [m, h, dom, mon, dow] = expr.trim().split(/\s+/);
  return (
    matchesValue(m, date.getMinutes(), 0, 59) &&
    matchesValue(h, date.getHours(), 0, 23) &&
    matchesValue(dom, date.getDate(), 1, 31) &&
    matchesValue(mon, date.getMonth() + 1, 1, 12) &&
    matchesValue(dow, date.getDay(), 0, 6)
  );
}

export function nextRun(expr, from = new Date()) {
  if (!validateCron(expr).valid) return null;
  const d = new Date(from.getTime() + 60_000 - (from.getSeconds() * 1000 + from.getMilliseconds()));
  for (let i = 0; i < 366 * 24 * 60; i++) {
    if (cronMatches(expr, d)) return d.toISOString();
    d.setMinutes(d.getMinutes() + 1);
  }
  return null;
}

export function describeCron(expr) {
  const presets = {
    '0 9 * * *': 'Every day at 9:00 AM',
    '0 */6 * * *': 'Every 6 hours',
    '0 9 * * 1': 'Every Monday at 9:00 AM',
    '0 9 1 * *': 'On the 1st of every month at 9:00 AM',
  };
  if (presets[expr]) return presets[expr];
  const [m, h] = expr.split(/\s+/);
  if (/^\d+$/.test(m) && /^\d+$/.test(h)) {
    return `Daily at ${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
  }
  return `Cron: ${expr}`;
}

// ── GitHub Actions workflow generation ──────────────────────────────────────
// Mirrors AlphaPost's model: the schedule lives in the user's own GitHub repo
// (a workflow named alphapost-cron) which calls the engine on each tick.
export function generateWorkflow(order) {
  const id = order.id;
  const cron = order.schedule || '0 9 * * *';
  return `# Auto-generated by AlphaPost clone. Do not edit by hand.
name: alphapost-cron
on:
  schedule:
    - cron: '${cron}'
  workflow_dispatch: {}
jobs:
  post:
    runs-on: ubuntu-latest
    steps:
      - name: Trigger AlphaPost order
        run: |
          curl -fsS -X POST "\${{ secrets.ALPHAPOST_BASE_URL }}/api/orders/${id}/run" \\
            -H "Authorization: Bearer \${{ secrets.ALPHAPOST_ORDER_TOKEN }}" \\
            -H "Content-Type: application/json" \\
            -d '{"source":"github-actions"}'
`;
}

// ── Order execution ─────────────────────────────────────────────────────────
export async function runOrder(order, { source = 'manual' } = {}) {
  const user = db.users.byId(order.userId);
  if (!user) return { ok: false, error: 'Order owner not found' };

  const accounts = (order.accountIds || [])
    .map((id) => db.accounts.byId(id))
    .filter((a) => a && a.userId === order.userId && a.status === 'connected');
  if (!accounts.length) return { ok: false, error: 'No connected accounts for this order' };

  const generated = await writeContent({
    user,
    inlineKey: order.inlineKey || '',
    kind: 'article',
    topic: order.topic,
    tone: order.tone || 'friendly',
    words: order.words || 700,
    category: order.category || '',
    audience: order.audience || '',
    extra: order.prompt || '',
  });

  const content = { title: generated.title, body: generated.body, tags: generated.tags, mediaUrl: order.mediaUrl || '' };

  const results = [];
  for (const account of accounts) {
    const res = await publishToAccount(hydrate(account), content);
    results.push(res);
    await db.posts.insert({
      userId: order.userId,
      orderId: order.id,
      accountId: account.id,
      platform: account.platform,
      title: generated.title,
      body: generated.body,
      tags: generated.tags,
      status: res.ok ? (res.status || 'published') : 'failed',
      provider: generated.provider,
      mocked: Boolean(res.mocked || generated.mocked),
      externalId: res.externalId || null,
      url: res.url || null,
      error: res.error || null,
      source,
    });
    if (res.ok) await bumpStat('posts_sent');
  }

  if (order.kind === 'blogger' || accounts.some((a) => a.platform === 'blogger')) {
    if (results.some((r) => r.ok && r.platform === 'blogger')) await bumpStat('articles_published');
  }

  await db.orders.update(order.id, { lastRunAt: new Date().toISOString(), lastRunSource: source, lastStatus: results.every((r) => r.ok) ? 'ok' : 'partial' });
  await logEvent(order.userId, 'order.run', { orderId: order.id, source, count: results.length });
  return { ok: true, title: generated.title, provider: generated.provider, mocked: generated.mocked, results };
}

// Publish any composer posts whose scheduled time has arrived.
export async function tickScheduledPosts(now = new Date()) {
  const due = db.posts.filter(
    (p) => p.status === 'scheduled' && p.scheduledFor && new Date(p.scheduledFor).getTime() <= now.getTime(),
  );
  const done = [];
  for (const post of due) {
    const accountIds = post.accountIds || (post.accountId ? [post.accountId] : []);
    const results = [];
    for (const id of accountIds) {
      const account = db.accounts.byId(id);
      if (!account) continue;
      const res = await publishToAccount(hydrate(account), { title: post.title, body: post.body, tags: post.tags, mediaUrl: post.mediaUrl });
      results.push(res);
      await db.posts.insert({
        userId: post.userId,
        accountId: account.id,
        platform: account.platform,
        title: post.title,
        body: post.body,
        tags: post.tags,
        status: res.ok ? (res.status || 'published') : 'failed',
        mocked: Boolean(res.mocked),
        externalId: res.externalId || null,
        url: res.url || null,
        error: res.error || null,
        source: 'scheduler',
      });
      if (res.ok) await bumpStat('posts_sent');
    }
    await db.posts.update(post.id, { status: 'published', publishedAt: now.toISOString(), results });
    done.push({ postId: post.id, results });
  }
  return done;
}

// Advance any orders whose schedule is due (called by the in-process ticker).
export async function tick(now = new Date()) {
  const runs = [];
  for (const order of db.orders.filter((o) => o.status === 'active')) {
    if (!order.schedule) continue;
    // Debounce: don't run twice within the same minute.
    const last = order.lastRunAt ? new Date(order.lastRunAt) : null;
    if (last && now.getTime() - last.getTime() < 60_000) continue;
    if (!cronMatches(order.schedule, now)) continue;
    runs.push(await runOrder(order, { source: 'scheduler' }));
    await db.orders.update(order.id, { nextRunAt: nextRun(order.schedule, now) });
  }
  return runs;
}
